  /** Graph hook: decorate node labels with renames from enabled layers (≈ human, ✦ AI draft). */
  function applyOverlay(data) {
    if (!data || !data.nodes) return data;
    data.nodes.forEach(function (n) {
      if (n._p3label != null) { n.label = n._p3label; delete n._p3label; }
      var o = overlayFor(n.inspect_name || n.id);
      if (o) { n._p3label = n.label; n.label = (o.ai ? "✦ " : "≈ ") + o.rename; }
    });
    return data;
  }

