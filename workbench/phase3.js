/* ==========================================================================
   phase3.js — leanre Phase 3 views: Kernel-Exact, FLIRT, Annotation Packs
   Vanilla JS, no external dependencies. Talks to workbench/phase3.py routes.

   Guardrails enforced here (research/04 §2, docs/PHASE3_GATES.md W1-W2/R3):
     * every statistic is rendered through stat()/srcLine() and so carries an
       [L] "extracted" tag plus its source, or a SYNTHETIC FIXTURE tag;
     * fixture data raises a permanent, non-dismissable banner;
     * Tier 3 output and ai-draft annotation layers are always marked
       "AI DRAFT" and styled apart; ai-draft layers are OFF by default;
     * absent producers render an explicit "Not built yet" panel, no numbers;
     * copy describes kernel facts as dependency facts about the export —
       never as a verdict on the theorem itself.
   ========================================================================== */
