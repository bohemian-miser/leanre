  /** Pull the input file, its hashes and the counting rule out of kernel.db's meta table. */
  function metaInput(meta) {
    var out = { file: "", shas: [], rule: "" };
    (function walk(obj, prefix, depth) {
      if (!obj || typeof obj !== "object" || depth > 3) return;
      Object.keys(obj).forEach(function (k) {
        var v = obj[k], key = prefix ? prefix + "." + k : k;
        if (typeof v === "string") {
          if (/sha256/i.test(key) && /^[0-9a-f]{64}$/i.test(v)) out.shas.push([key, v]);
          else if (!out.file && /(^|\.)(path|file|file_name|input)$/i.test(key)) out.file = v;
          else if (!out.rule && /counting_rule/i.test(key)) out.rule = v;
        } else walk(v, key, depth + 1);
      });
    })(meta, "", 0);
    return out;
  }

